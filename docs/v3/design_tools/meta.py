import math
start=[0.42,0.58,1.33,2.33,3.88,6.33,8.88,11.88,15.54,19.33,23.33,27.33,31.33,35.33,39.33,43.33,47.54,52.54,57.54,62.33,67.88,73.33,79.33,85.33]
for k,D in enumerate(start,1):
    b=1+0.10*(k-1)+0.02*(k-1)*min(3,D/25)
    rl=min(25,1.9*D**0.5) if D>=0.8 else 0
    r=1+0.05*rl
    z=(k-1)*0.8+max(0,D-4)/7*2.2+math.floor(D/28)
    zm=1.05**z
    h=1+min(0.3,0.002*D)
    c=1+(0.3+0.012*D if D>=0.4 else 0)
    M=b*r*zm*h*c
    S=max(1,M/3)
    print(k, round(D,1), f"b={b:.2f} r={r:.2f} z={z:.1f}({zm:.2f}) h={h:.2f} c={c:.2f} M={M:.1f} S={S:.2g}")
